-- Verifica quais bots precisam inserir o EXTERNAL ID (6.1.9 da lib Nubank) considerando o mes presente e o mes anterior
SELECT DISTINCT ID_BOT
FROM RPA.RPA_AA_GERENCIADOR_EXECUCOES
WHERE ID_BOT IN (
		SELECT gr.ID 
		FROM RPA.RPA_AA_GERENCIADOR_ROBOS gr
		WHERE BU = 'Brazil - Operations'
			AND gr.ENABLE = '1')
	AND EXTERNAL_ID IS NULL
	AND ID_BOT NOT IN (SELECT ID_BOT
FROM RPA.RPA_AA_GERENCIADOR_EXECUCOES
WHERE ID_BOT IN (
		SELECT gr.ID 
		FROM RPA.RPA_AA_GERENCIADOR_ROBOS gr
		WHERE BU = 'Brazil - Operations'
			AND gr.ENABLE = '1')
	AND EXTERNAL_ID IS NOT NULL
	AND TO_CHAR(TO_DATE(END_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM/yyyy') = TO_CHAR(SYSDATE, 'MM/yyyy'))
	AND TO_CHAR(TO_DATE(END_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM/yyyy') = TO_CHAR(SYSDATE, 'MM/yyyy')
ORDER BY ID_BOT ASC;
