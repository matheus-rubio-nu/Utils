SELECT execs.ID_BOT 
	,execs.INI_EXECUTION 
	,execs.STATUS 
FROM RPA.RPA_AA_GERENCIADOR_EXECUCOES execs
WHERE ID_BOT = 21
ORDER BY execs.ID_EXECUTION DESC;

SELECT 
    TO_CHAR(TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM'), 'MM/yyyy') AS PERIOD
  , ID_BOT 
  , COUNT(*) AS QTDE_SUCESSO
FROM RPA.RPA_AA_GERENCIADOR_EXECUCOES execs
INNER JOIN RPA.RPA_AA_GERENCIADOR_ROBOS gr
ON gr.ID =  execs.ID_BOT 
WHERE execs.STATUS = 1
	AND gr.BU = 'Brazil - Operations'
	AND INI_EXECUTION IS NOT NULL
GROUP BY 
    ID_BOT
  , TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM')
ORDER BY 
	ID_BOT ASC
    , TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM') ASC;

SELECT --Qtde de erros por bot/periodo dos bots que eu tive mais atuacao
    TO_CHAR(TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM'), 'MM/yyyy') AS PERIOD
  , ID_BOT 
  , COUNT(*) AS QTDE_EXECS
  , COUNT(CASE WHEN execs.STATUS = 1 THEN 1 END) AS QTDE_SUCESSO
  , COUNT(CASE WHEN execs.STATUS NOT IN (1, 5) THEN 1 END) AS QTDE_ERROS
  , COUNT (execs.COUNT_EXEC) AS QTDE_ITENS
FROM RPA.RPA_AA_GERENCIADOR_EXECUCOES execs
INNER JOIN RPA.RPA_AA_GERENCIADOR_ROBOS gr
   ON gr.ID = execs.ID_BOT 
WHERE gr.BU = 'Brazil - Operations'
  AND INI_EXECUTION IS NOT NULL
  AND ID_BOT IN (21, 35, 85, 130, 144, 196, 201, 208)
GROUP BY 
    ID_BOT
  , TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM')
ORDER BY 
    ID_BOT ASC
  , TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM') ASC;

------------TEMPO MEDIO DE EXEC
SELECT 
	TO_CHAR(TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM'), 'MM/yyyy') AS PERIOD
	,ID_BOT
	,ROUND(
    	AVG(
	        (TO_DATE(END_EXECUTION, 'DD/MM/YYYY HH24:MI:SS') - 
	         TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS')) * 24
    	)
	, 2) AS TEMPO_EXEC_HORA_DOUBLE
FROM RPA.RPA_AA_GERENCIADOR_EXECUCOES
WHERE ID_BOT IN (130)
GROUP BY ID_BOT
	, TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM')
ORDER BY TRUNC(TO_DATE(INI_EXECUTION, 'DD/MM/YYYY HH24:MI:SS'), 'MM') ASC;




